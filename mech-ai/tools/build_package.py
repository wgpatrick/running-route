"""Build package for a printer design: everything needed to buy, fabricate, assemble, wire and commission it.

    .venv/bin/python tools/build_package.py designs/printer_v8.py [--out docs/build] [--report-root out]
                     [--force] [--rerun-assembly] [--no-drawings] [--no-images] [--only bom,fab,asm,wiring,comm,open,readme]

Everything is generated from the design file (build() -> Design), the last FULL verify report
(<report-root>/<name>/report.json), the scorecard (scores.jsonl), `mechloop tune` (tune/tuning.json) and the electrical
verifier's outputs (electrical/). Numbers the design or the report hold are read, never typed here. What lives in this
file is judgement and wording: which catalogue lines are stand-ins (STANDIN_RULES), how tolerance-model figures become
drawing tolerances (TOL_K), the curated open items that only exist as prose in docs/<NAME>.md (CURATED_OPEN_ITEMS),
and the procedures. Those are marked "generator" where they appear.

The generator REFUSES to run when the report does not describe the design file (part count, mass, bounding box, BOM
quantities, custom part list); --force writes the package anyway with a STALE banner on every document.

mechloop is imported read-only. Nothing under mechloop/, tests/ or designs/ is written.
"""
