    belts = dig(m, "motion", "belts", default={})
    wires = list(csv.DictReader(open(cx.eldir / "wiring.csv"))) if (cx.eldir / "wiring.csv").exists() else []
    bom["wires"] = wires
    tl = thread_length_issues(cx)
    bom["thread_length_issues"] = tl
    # ---- markdown
