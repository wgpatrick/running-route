SPARE_FRAC = 0.10


# ------------------------------------------------------------------------------------------------ small helpers
def rel(p) -> str:
    """Path as text, relative to the repository when it is inside it."""
    p = Path(p)
    return str(p.relative_to(ROOT)) if p.is_absolute() and p.is_relative_to(ROOT) else str(p)


def md5_of(path: Path) -> str:
    return hashlib.md5(Path(path).read_bytes()).hexdigest()


def f2(x, n=2):
    if x is None:
        return "not specified"
    if isinstance(x, str):
        return x
    s = f"{float(x):.{n}f}"
    return s.rstrip("0").rstrip(".") if "." in s else s


def money(x):
    return "not specified" if x is None else f"{float(x):.2f}"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in r) + " |")
    return "\n".join(out)


def dig(d, *keys, default=None):
    for k in keys:
        if isinstance(d, dict) and k in d:
            d = d[k]
        else:
            return default
    return d


class Ctx:
    """Everything the writers read."""

    def __init__(self, design_path: Path, out_root: Path, report_root: Path, force: bool):
        from mechloop.runner import load_design

        self.design_path = Path(design_path).resolve()
        self.d = load_design(self.design_path)
        self.name = self.d.name
        self.out = Path(out_root) / self.name
        self.rdir = Path(report_root) / self.name
        self.rpath = self.rdir / "report.json"
        if not self.rpath.exists():
            sys.exit(f"REFUSED: {self.rpath} not found. Run `python -m mechloop verify {design_path}` (full run) first.")
        self.rep = json.loads(self.rpath.read_text())
        self.m = self.rep["metrics"]
        self.md5 = md5_of(self.design_path)
        self.report_time = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(self.rpath.stat().st_mtime))
        self.report_md5 = md5_of(self.rpath)
        self.comps = {c.name: c for c in self.d.components}
        self.fast = {f.name: f for f in self.d.fasteners}
        sp = self.rdir / "scores.jsonl"
        self.score = None
        if sp.exists():
            lines = [json.loads(x) for x in sp.read_text().strip().splitlines() if x.strip()]
            full = [s for s in lines if "resonance_hz" in s]      # the built-in planner's scorecard (not --firmware-only)
            self.score = full[-1] if full else None
            fw = [s for s in lines if s.get("klipper")]
            self.score_fw = fw[-1] if fw else None
        tp = self.rdir / "tune" / "tuning.json"
        self.tune = json.loads(tp.read_text()) if tp.exists() else None
        self.eldir = self.rdir / "electrical"
        self.stale = []
        self.force = force
        self.needed = []          # "needed from the design": data the package wanted and the design / catalogue does not hold
        self.problems = []        # things found wrong or doubtful while generating (also written to OPEN_ITEMS.md)

    # -- provenance stamp put at the top of every document
    def stamp(self) -> str:
        s = (f"Generated by `tools/build_package.py` from `{self.design_path.relative_to(ROOT)}` (md5 `{self.md5}`) and "
             f"`{self.rpath.relative_to(ROOT) if self.rpath.is_relative_to(ROOT) else self.rpath}` (written {self.report_time}, md5 `{self.report_md5[:12]}`). "
             f"Do not edit: change the design, re-run verify, re-run the generator.")
        if self.stale:
            s = ("> **STALE PACKAGE (--force): the report does not describe this design file.** " + "; ".join(self.stale) + "\n\n") + s
        return s + "\n\n> **Simulated design. Nothing has been built.** See [OPEN_ITEMS.md](OPEN_ITEMS.md) before spending money.\n"

    def need(self, what: str, why: str):
        if (what, why) not in self.needed:
            self.needed.append((what, why))

    def problem(self, rank: str, title: str, detail: str, check: str = ""):
        self.problems.append({"rank": rank, "title": title, "detail": detail, "check": check})


def bom_of_design(d) -> dict:
    """SKU -> qty exactly as the ratings verifier counts it (components by SKU, plus design.bom_extras)."""
    q = Counter()
    for c in d.components:
        if c.cots:
            q[c.sku or c.name] += 1
    for sku, e in d.bom_extras.items():
        q[sku] += e["qty"]
    return dict(q)


def check_fresh(cx: Ctx) -> None:
    """Does report.json describe this design file? The report carries no hash of the design, so its own content is
    compared with the design as built now."""
    d, m = cx.d, cx.m
    bad = []
    g = m.get("geometry", {})
    if g.get("parts") != len(d.components):
        bad.append(f"part count: report {g.get('parts')}, design {len(d.components)}")
    mass = sum(c.mass() for c in d.components)
    if g.get("mass_kg") is None or abs(g["mass_kg"] - mass) > 0.002:
        bad.append(f"mass: report {g.get('mass_kg')} kg, design {mass:.4f} kg")
    rb = dig(m, "ratings", "bom", default={})
    mine = bom_of_design(d)
    diff = sorted(k for k in set(rb) | set(mine) if dig(rb, k, "qty") != mine.get(k))
    if diff:
        bad.append("BOM quantities differ for " + ", ".join(f"{k} (report {dig(rb, k, 'qty')}, design {mine.get(k)})" for k in diff[:8]))
    custom = sorted(c.name for c in d.components if not c.cots)
    rc = dig(m, "ratings", "custom_parts", default=[])
    if (len(custom) != rc) if isinstance(rc, int) else (sorted(rc) != custom):     # newer reports give the count only
        bad.append("custom part list differs")
    summ = cx.rep.get("summary", {})
    if cx.rep.get("partial") or len(summ) < 12:
        bad.append(f"report is not a full run ({len(summ)} verifiers)")
    cx.warnings = []
    cx.doc_md5_ok = None
    if cx.design_path.stat().st_mtime > cx.rpath.stat().st_mtime + 1:
        cx.warnings.append("the design file's modification time is LATER than the report's (content checks passed; a checkout also does this)")
    doc = ROOT / "docs" / f"{cx.name.upper()}.md"
    if doc.exists():
        mm = re.search(r"md5 ([0-9a-f]{8})", doc.read_text())
        if mm and not cx.md5.startswith(mm.group(1)):
            cx.warnings.append(f"{doc.name} records the verified file as md5 {mm.group(1)}..., this file is {cx.md5[:8]}...")
        elif mm:
            cx.doc_md5_ok = mm.group(1)
    if not cx.rep.get("ok"):
        bad.append("the report is not a pass (errors present)")
    # the parts catalogue is code too: has it changed since the report was written? (a warning: quantities still agree)
    drift = []
    now_backed = sorted({c.sku or c.name for c in d.components if c.cots and c.meta.get("vendor_backed")})
    was_backed = sorted(dig(m, "ratings", "vendor_backed_parts", default=[]))
    if now_backed != was_backed:
        drift.append("vendor-backed parts: now also " + ", ".join(sorted(set(now_backed) - set(was_backed)) or ["none"]) + "; no longer " + ", ".join(sorted(set(was_backed) - set(now_backed)) or ["none"]))
    seen = {}
    for c in d.components:
        if c.cots and (c.sku or c.name) not in seen:
            seen[c.sku or c.name] = c
    for sku, c in seen.items():
        r_ = rb.get(sku, {})
        if r_.get("unit_cost_usd") is not None and c.meta.get("cost_usd") is not None and abs(r_["unit_cost_usd"] - c.meta["cost_usd"]) > 1e-6:
            drift.append(f"{sku} unit cost: report {r_['unit_cost_usd']}, catalogue now {c.meta['cost_usd']}")
        if r_.get("mcmaster_pn_status") != c.ratings.get("mcmaster_pn_status"):
            drift.append(f"{sku} McMaster status: report '{str(r_.get('mcmaster_pn_status'))[:50]}', catalogue now '{str(c.ratings.get('mcmaster_pn_status'))[:50]}'")
        if abs((r_.get("mass_kg") or 0) - sum(x.mass() for x in d.components if (x.sku or x.name) == sku)) > 5e-4:
            drift.append(f"{sku} mass differs from the report")
    if drift:
        cx.warnings.append("the parts catalogue has changed since the report was written (the package uses the catalogue as it is NOW; re-run verify to make the report agree): " + "; ".join(drift[:12]))
    if bad:
        msg = "report.json does not match the design file:\n  - " + "\n  - ".join(bad)
        if not cx.force:
            sys.exit("REFUSED: " + msg + f"\nRun `python -m mechloop verify {rel(cx.design_path)}` (full) and re-run, or pass --force "
                     "to write a package marked STALE.")
        print("WARNING (--force): " + msg, file=sys.stderr)
        cx.stale = bad
    for w in cx.warnings:
        print("WARNING: " + w, file=sys.stderr)


